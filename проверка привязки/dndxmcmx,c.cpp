#include <iostream>
#include <string> // Подключаем библиотеку для работы с текстом

int main() {
    // Создаем переменные для хранения имени и возраста
    std::string name;
    int age;

    // Спрашиваем имя
    std::cout << "Введите ваше имя: ";
    std::cin >> name; // Считываем имя, которое ввел пользователь

    // Спрашиваем возраст
    std::cout << "Привет, " << name << "! Сколько вам лет? ";
    std::cin >> age; // Считываем возраст

    // Проверяем условие (например, права можно получить с 18 лет)
    if (age >= 18) {
        std::cout << "Отлично, " << name << ", вы уже можете водить автомобиль!\n";
    } else {
        int yearsLeft = 18 - age;
        std::cout << "Вам пока нельзя водить. Подождите еще " << yearsLeft << " года/лет.\n";
    }

    return 0;
}
