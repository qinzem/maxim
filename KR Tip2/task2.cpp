#include <iostream>

// Рекурсивная функция для вычисления НОД (по алгоритму Евклида)
int find_gcd(int a, int b) {
    // Базовый случай: если одно из чисел стало нулем, 
    // то НОДом является второе число (на него делились без остатка)
    if (b == 0) {
        return a;
    }
    
    // Рекурсивный шаг: вызываем функцию снова, 
    // но вместо большего числа берем остаток от деления (a % b)
    return find_gcd(b, a % b);
}

int main() {
    int a, b;
    
    // Считываем два натуральных числа из ввода
    std::cin >> a >> b;
    
    // Вызываем нашу функцию и выводим результат
    std::cout << find_gcd(a, b) << std::endl;
    
    return 0;
}