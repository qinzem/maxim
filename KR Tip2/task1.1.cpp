#include <iostream>
// Функция быстрого возведения в степень (рекурсивный метод)
long long power_rec(long long a, long long n) {
    if (n == 0) {
        return 1;
    }
    if (n % 2 == 0) {
        // Сначала рекурсивно вычисляем половину степени: a^(n/2)
        long long half = power_rec(a, n / 2);
        // Затем возводим полученный результат в квадрат: (a^(n/2))^2 = a^n
        return half * half;
    } 
    // Если степень нечетная
    else {
        // Выносим одно основание 'a' вперед, а для оставшейся степени (n-1) 
        // вызываем функцию снова. Так мы делаем степень четной на следующем шаге.
        return a * power_rec(a, n - 1);
    }
}
int main() {
    // Вызываем функцию и выводим результат (10 в 12 степени)
    std::cout << power_rec(10, 12) << std::endl; 
    return 0;
}