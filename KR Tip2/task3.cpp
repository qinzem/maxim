#include <iostream> // Подключаем библиотеку для ввода/вывода

// Функция для перекладывания башни из n блинов
void hanoi(int n, int from, int to, int aux) { // from - откуда, to - куда, aux - вспомогательная
    
    if (n == 0) return; // Базовый случай: если блинов нет, просто выходим

    hanoi(n - 1, from, aux, to); // Шаг 1: Переносим верхние (n-1) блинов на вспомогательную колонку

    std::cout << "Ingredient " << n << " move from " << from << " to " << to << "\n"; // Печатаем перенос самого нижнего (n-го) блина на финиш

    hanoi(n - 1, aux, to, from); // Шаг 3: Переносим те (n-1) блинов со вспомогательной колонки на финиш
} // Конец функции hanoi

int main() { // Точка входа в программу
    int n; // Переменная для количества блинов
    std::cin >> n; // Считываем количество блинов с клавиатуры

    hanoi(n, 1, 3, 2); // Запускаем перекладывание: n блинов с 1-й колонки на 3-ю (2-я — вспомогательная)

    return 0; // Успешное завершение программы
} // Конец функции main